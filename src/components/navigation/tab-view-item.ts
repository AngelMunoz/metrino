import { LitElement, html, css } from "lit";
import { reducedMotionBlanket } from "../../styles/shared.ts";

/**
 * Metro Tab View Item Component
 *
 * A child component for MetroTabView that owns one tab: the `header` text
 * labels the tab strip entry, an optional `[slot="icon"]` child decorates it,
 * and the default slot is the tab panel content shown when selected.
 *
 * Use as children of metro-tab-view. Set the "header" attribute to define
 * the tab label text and add "closable" to render a close button for the tab.
 *
 * @slot icon - Optional icon content projected into the tab strip entry
 * @slot - Default slot for the tab panel content
 *
 * @cssprop --metro-spacing-md - Medium spacing for content padding (default: 12px)
 */
export class MetroTabViewItem extends LitElement {
  static properties = {
    /**
     * Text displayed in the tab strip entry.
     * If not set, a default "Tab N" label is generated by the parent.
     * @default ""
     */
    header: { type: String, reflect: true },
    /**
     * When set, the tab strip entry renders a close button for this tab.
     * @default false
     */
    closable: { type: Boolean, reflect: true },
  };

  declare header: string;
  declare closable: boolean;

  static styles = [
    reducedMotionBlanket,
    css`
      :host {
        display: block;
        padding: var(--metro-spacing-md, 12px);
        box-sizing: border-box;
      }
      :host(:not([active])) {
        display: none;
      }
      .icon-sink {
        display: none;
      }
    `,
  ];

  constructor() {
    super();
    this.header = "";
    this.closable = false;
  }

  render() {
    return html`<slot name="icon" class="icon-sink"></slot><slot></slot>`;
  }
}

export function registerMetroTabViewItem(): void {
  if (!customElements.get("metro-tab-view-item")) {
    customElements.define("metro-tab-view-item", MetroTabViewItem);
  }
}

declare global {
  interface HTMLElementTagNameMap {
    "metro-tab-view-item": MetroTabViewItem;
  }
}
